(* The SIN32 statement: a CANDIDATE, drafted 2026-11-15 before its proof and before any compilation, its header
   reworded 2026-11-16 after two readings (no Definition changed); not adopted.
   Graph.v is generated by sin32/emit_sin32.py from the one table of steps it also evaluates with Python floats.
   Against the prototype's g_sin32 the table leaves out one operation, the first level's product u * 1.0, which is
   exact; Graph.v's own header does not say so.
   Model: Flocq's FLT formats, binary64 as FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper exponent
   bound, so no overflow, and the sign of a zero is not seen. sin is the standard library's (Rtrigo_def). Author: the
   assistant.

   WHAT IT SAYS.
   SIN32         for every binary32 x of magnitude at most SMAX, the graph g_sin32 returns a faithful binary32 rounding
                 of sin x: one of the two binary32 values that bracket sin x (sin x itself when it is representable).
   SIN32_FINITE  for the same x the result is a finite binary32 number (in the format, magnitude at most FMAX32).
                 It is not an independent claim: it follows from SIN32, |sin x| <= 1 and p32r's FAITHFUL_FINITE.
   SIN32_ALL     both.
   SMAX = 13176795 / 2^23 = 1.57079637050628662109375 (bits 3FC90FDB) is the binary32 number nearest pi/2. It is
   slightly ABOVE pi/2 (by about 4.4e-8), so the domain is a little more than a quarter turn each way. That SMAX has
   those bits, and that it is the nearest binary32 number to pi/2, are not part of this statement.

   WHAT IT DOES NOT SAY.
   - The sign of a zero. The model has one zero: for x = -0 it says the result is zero, not which zero.
   - Anything for an input outside the premises: |x| above SMAX (no reduction of the argument is done; the polynomial
     leaves sin behind as |x| grows), a NaN or an infinity (the model has neither).
   - Anything about a program, a compiler or a machine. It is about the Coq graph of Graph.v; that a program computes
     that graph with IEEE binary64 operations is another layer and is not shown here.
   - That the result is correctly rounded. Faithful allows either neighbour of sin x, and which one is not said.
   - That no binary64 operation of the graph overflows or underflows. Overflow is absent from the model; that every
     intermediate value stays far inside binary64's range is argued in DESIGN.md, not stated here.
   - That the graph is odd (g_sin32 (-x) = - g_sin32 x) or monotone, or that the result equals x for a small x.
   - As a Prop of its own, that the result is at most 1 in magnitude. SIN32 implies it (1 is a binary32 number and
     |sin x| <= 1, so both values that bracket sin x lie between -1 and 1), but no definition here states it;
     SIN32_FINITE states only the far weaker bound FMAX32.
   - That the premise cannot be widened: no sharpness statement is made about SMAX.

   WHAT IT TRUSTS. Coq's kernel and the tier's four axioms (the classical reals: sig_not_dec and
   sig_forall_dec; functional extensionality: functional_extensionality_dep; classical logic: classic); Flocq's
   definitions of generic_format, FLT_exp and round; the standard library's definition of sin; the definitions it
   imports (format32 and faithful32 from f32, finite32 and FMAX32 from p32r, RN64 and narrow from p32 through Graph.v);
   and that Graph.v is the graph meant, which rests on the generator and on a reader.

   THE PREMISES, one line each.
   format32 x       x is a number of the binary32 format (in this model: of any magnitude; the next line bounds it).
   Rabs x <= SMAX   the magnitude of x is at most SMAX: x lies between -SMAX and SMAX, both ends included. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.p32r Require Import P32R_Statement.
From MKF.sin32 Require Import Graph.
Open Scope R_scope.

Definition SMAX : R := 13176795 / 8388608.

Definition SIN32 : Prop :=
  forall x : R, format32 x -> Rabs x <= SMAX -> faithful32 (sin x) (g_sin32 x).

Definition SIN32_FINITE : Prop :=
  forall x : R, format32 x -> Rabs x <= SMAX -> Rabs (g_sin32 x) <= / 2.

Definition SIN32_ALL : Prop := SIN32 /\ SIN32_FINITE.
