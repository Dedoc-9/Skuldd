# sin32, a candidate function (drafted 2026-11-15; nothing here is adopted). One table of steps, two renderings.
#   sin32(x) = narrow(x * P(x * x)) for a binary32 x with |x| <= SMAX (13176795 / 2^23, bits 3FC90FDB), where
#   P(u) = 1 - u/6 (1 - u/20 (1 - u/42 (1 - u/72 (1 - u/110 (1 - u/156 (1 - u/210)))))) is the Taylor polynomial of
#   sin through x^15, divided by x, in nested form. Every constant is a whole number; every operation is one binary64
#   operation (round to nearest even). The graph is the prototype's g_sin32 (ext-work/proto/proto.py), not redesigned.
#   python -B emit_sin32.py coq [-]   the Coq graph, Graph.v ("-": to stdout, byte for byte; else beside this script)
#   python -B emit_sin32.py py [-]    reads lines "<8 hex digits>" (a binary32 bit pattern) from stdin and prints
#                                     "<input> <16 hex: the binary64 value before narrow> <8 hex: the binary32 result>"
# Standard library only. Author: the assistant.
import decimal, os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SMAX_U = 0x3FC90FDB                       # the binary32 number nearest pi/2; it is slightly above pi/2
DIVISORS = ('156.0', '110.0', '72.0', '42.0', '20.0', '6.0')
def lvl(c): return ('poly', 't', ('sub', ('const', '1.0'), ('div', ('mul', ('var', 'u'), ('var', 't')), ('const', c))))
STEPS = (    # (stage, target, tree): THE table. Stage 'sq' reads x; 'poly' reads u; 'out' reads x and t.
    [('sq', 'u', ('mul', ('var', 'x'), ('var', 'x'))),
     ('poly', 't', ('sub', ('const', '1.0'), ('div', ('var', 'u'), ('const', '210.0'))))]
    + [lvl(c) for c in DIVISORS]
    + [('out', 'y', ('mul', ('var', 'x'), ('var', 't')))])
OPS = {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}

def py_tree(e, env):
    if e[0] == 'var': return env[e[1]]
    if e[0] == 'const': return float(e[1])
    a, b = py_tree(e[1], env), py_tree(e[2], env)
    return a + b if e[0] == 'add' else a - b if e[0] == 'sub' else a * b if e[0] == 'mul' else a / b
def py_env(x):
    """Every step of the table with Python floats (binary64, round to nearest even); returns the final environment."""
    env = {'x': x}
    for _, t, e in STEPS: env[t] = py_tree(e, env)
    return env
def py_trace(x):
    """The value of t after each 'poly' step, in order (seven values)."""
    env = {'x': x}; tr = []
    for st, t, e in STEPS:
        env[t] = py_tree(e, env)
        if st == 'poly': tr.append(env[t])
    return tr
def py_y(x): return py_env(x)['y']                      # the binary64 value before narrow
def narrow(v): return struct.unpack('<f', struct.pack('<f', v))[0]       # the IEEE conversion, as proto.py has it
KK, MM, TT, HH = 536870913.0, 1.5 * 2.0 ** -97, 2.0 ** -126, 2.0 ** -150
def py_narrow(v):                                       # p32's narrow graph (mkf/p32/Graphs.v), binary64 operations only
    if abs(v) <= HH: return v * 0.0
    if abs(v) < TT: return (v + MM) - MM
    c = KK * v
    return c - (c - v)
def py_g(x): return narrow(py_y(x))
def f32(u): return struct.unpack('<f', struct.pack('<I', u))[0]
def u32(x): return struct.unpack('<I', struct.pack('<f', x))[0]
def bits(d): return struct.unpack('<Q', struct.pack('<d', d))[0]

def coq_const(s):
    d = decimal.Decimal(s); assert d == d.to_integral_value() and d >= 0, s
    return '%d' % int(d)
def coq_tree(e, env):
    if e[0] == 'var': return env[e[1]]
    if e[0] == 'const': return coq_const(e[1])
    return '(RN64 (%s %s %s))' % (coq_tree(e[1], env), OPS[e[0]], coq_tree(e[2], env))
def strip(b): return b[1:-1] if b.startswith('(') and b.endswith(')') else b
def coq_text():
    """The Coq graph from the table: every binary64 operation is one RN64 of its exact operands; a stage is a
    definition of its input with its steps substituted in order; the function is narrow of the last step."""
    L = ['(* Generated by sin32/emit_sin32.py coq; do not edit. The operation graph of sin32 in the FLT model of binary64',
         '   (no overflow, no sign of zero), from the one table of steps that the script also evaluates with Python floats.',
         '   sin32_sq: x * x. sin32_poly: the nested form 1 - u/6 (1 - u/20 (1 - u/42 (1 - u/72 (1 - u/110 (1 - u/156',
         '   (1 - u/210)))))), innermost first: the Taylor polynomial of sin through x^15, divided by x, at u = x^2.',
         '   g_sin32: narrow of x times that. *)',
         'From Coq Require Import Reals.', 'From Flocq Require Import Core.', 'From MKF.p32 Require Import Graphs.', 'Open Scope R_scope.', '']
    for name, var in (('sq', 'x'), ('poly', 'u')):
        env = {var: var}; out = None
        for st, t, e in STEPS:
            if st == name: env[t] = coq_tree(e, env); out = t
        L.append('Definition sin32_%s (%s : R) : R := %s.' % (name, var, strip(env[out])))
    env = {'x': 'x', 't': '(sin32_poly (sin32_sq x))'}
    outs = [(t, e) for st, t, e in STEPS if st == 'out']; assert len(outs) == 1
    L += ['', 'Definition g_sin32 (x : R) : R := narrow %s.' % coq_tree(outs[0][1], env)]
    return (chr(10).join(L) + chr(10)).encode('utf-8')
def coq():
    if len(sys.argv) > 2 and sys.argv[2] == '-': sys.stdout.buffer.write(coq_text())
    else: open(os.path.join(HERE, 'Graph.v'), 'wb').write(coq_text()); print('wrote Graph.v')
def py():
    out = []
    for line in sys.stdin.buffer.read().decode('ascii').split():
        u = int(line, 16); y = py_y(f32(u)); out.append('%08x %016x %08x' % (u, bits(y), u32(narrow(y))))
    sys.stdout.buffer.write((chr(10).join(out) + chr(10)).encode('ascii'))

if __name__ == '__main__':
    if len(sys.argv) >= 2 and sys.argv[1] in ('coq', 'py'): {'coq': coq, 'py': py}[sys.argv[1]]()
    else: print('usage: emit_sin32.py coq [-] | py [-]'); sys.exit(2)
