(* The COS32 statement: a CANDIDATE, drafted 2026-11-16 before its proof and before any compilation; not adopted.
   cos32 is built on sin32: cos x = sin (pi/2 - |x|). Graph.v is generated by cos32/emit_cos32.py from the one table
   of steps it also evaluates with Python floats; the square and the polynomial in it are sin32's own definitions
   (sin32_sq and sin32_poly of MKF.sin32.Graph), imported, not copied. Against the prototype's g_cos32_pre the graph
   leaves out one operation, the polynomial's first product u * 1.0, which is exact (it is sin32's graph that does).
   Model: Flocq's FLT formats, binary64 as FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper exponent
   bound, so no overflow, and the sign of a zero is not seen. cos is the standard library's (Rtrigo_def). Author: the
   assistant.

   WHAT IT SAYS.
   COS32         for every binary32 x of magnitude at most CMAX, the graph g_cos32 returns a faithful binary32 rounding
                 of cos x: one of the two binary32 values that bracket cos x (cos x itself when it is representable).
   COS32_FINITE  for the same x the result is a finite binary32 number (in the format, magnitude at most FMAX32).
                 It is not an independent claim: it follows from COS32, |cos x| <= 1 and p32r's FAITHFUL_FINITE.
   COS32_ALL     both.
   CMAX = 13176794 / 2^22 = 3.141592502593994140625 (bits 40490FDA) is the binary32 number just below the binary32
   number nearest pi. It is BELOW pi (by about 1.5e-7), so the domain is a little less than a half turn each way. That
   CMAX has those bits, and that it is that neighbour, are not part of this statement.

   WHAT IT DOES NOT SAY.
   - NO PERIODIC REDUCTION. This is cos on about [-pi, pi] only. For |x| above CMAX it says nothing: the graph does
     not bring a large argument back into range, and the polynomial leaves cos behind as |x| grows.
   - Anything for a NaN or an infinity (the model has neither).
   - The sign of a zero. The model has one zero. (For the inputs of the premises cos x is never zero, since pi/2 is
     not a binary32 number; that the result is never zero is not stated.) For x = -0 it says what it says for x = 0.
   - Anything about a program, a compiler or a machine. It is about the Coq graph of Graph.v; that a program computes
     that graph with IEEE binary64 operations, with these two constants, is another layer and is not shown here.
   - That the result is correctly rounded. Faithful allows either neighbour of cos x, and which one is not said.
     Where cos x is itself a binary32 number (x = 0, cos x = 1) faithful does mean the result is that number.
   - That no binary64 operation of the graph overflows or underflows. Overflow is absent from the model; that every
     intermediate value stays far inside binary64's range is argued in DESIGN.md, not stated here.
   - That the graph is even (g_cos32 (-x) = g_cos32 x; it is, since the graph reads x only through Rabs x, but no
     definition here states it), or monotone on either side of zero.
   - As a Prop of its own, that the result is at most 1 in magnitude. COS32 implies it (1 and -1 are binary32
     numbers and |cos x| <= 1); COS32_FINITE states only the far weaker bound FMAX32.
   - That the premise cannot be widened: no sharpness statement is made about CMAX.
   - Anything about pi. That cos32_PH + cos32_PL is close to pi/2, and that they are the nearest binary64 numbers to
     pi/2 and to the remainder, are not stated: a proof needs the first, and nothing needs the second.
   - Anything about sin32's statement. SIN32 is neither used nor implied here: cos32 gives sin32's polynomial an
     argument that is a binary64 number and in general not a binary32 one, which SIN32 does not cover.

   THE CONSTANTS ARE NOT WHOLE NUMBERS. Unlike the tier's other constants (sin32's divisors, narrow's KK), the two
   constants of the shift, in Graph.v, are binary64 numbers with fractional bits:
   cos32_PH = 7074237752028440 / 2^52 (0x1.921fb54442d18p+0) and cos32_PL = 4967757600021511 / 2^106
   (0x1.1a62633145c07p-54). A rendering of the graph must carry exactly these two numbers; a decimal literal that a
   compiler rounds differently would be another graph.

   WHAT IT TRUSTS. Coq's kernel and the tier's four axioms (the classical reals: sig_not_dec and
   sig_forall_dec; functional extensionality: functional_extensionality_dep; classical logic: classic); Flocq's
   definitions of generic_format, FLT_exp and round; the standard library's definitions of cos and Rabs; the
   definitions it imports (format32 and faithful32 from f32, finite32 and FMAX32 from p32r, RN64 and narrow from p32
   and sin32_sq and sin32_poly from sin32, all four through Graph.v); and that Graph.v is the graph meant, which rests
   on the generator and on a reader.

   THE PREMISES, one line each.
   format32 x       x is a number of the binary32 format (in this model: of any magnitude; the next line bounds it).
   Rabs x <= CMAX   the magnitude of x is at most CMAX: x lies between -CMAX and CMAX, both ends included. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.p32r Require Import P32R_Statement.
From MKF.cos32 Require Import Graph.
Open Scope R_scope.

Definition CMAX : R := 13176794 / 4194304.

Definition COS32 : Prop :=
  forall x : R, format32 x -> Rabs x <= CMAX -> faithful32 (cos x) (g_cos32 x).

Definition COS32_FINITE : Prop :=
  forall x : R, format32 x -> Rabs x <= CMAX -> finite32 (g_cos32 x).

Definition COS32_ALL : Prop := COS32 /\ COS32_FINITE.
