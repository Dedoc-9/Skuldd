# log32, a candidate staged function (2026-11-15). Author: the assistant. One table, two renderings.
#   log32(x) = narrow(k * P(Z(y))):  near := 15/16 <= x and x <= 17/16;  y := x if near, else twelve square roots of x
#   (y = x^(1/4096));  Z(y) = (y - 1) / (y + 1);  P(z) = (z * N(z*z)) / 105, N(w) = 105 + w(35 + w(21 + w*15)), which is
#   z(1 + w/3 + w^2/5 + w^3/7): atanh z through z^7 with whole coefficients;  k := 2 if near, else 8192 = 2 * 4096.
#   ln x = 4096 * ln y = 4096 * 2 * atanh((y - 1)/(y + 1)). No ln 2, no table, no exponent extraction.
#   python -B emit_log32.py coq -          prints log32/Graph.v to standard output, byte for byte
#   python -B emit_log32.py py <file|->    reads lines "log <8 hex digits>" (or bare hex), evaluates the SAME table with
#                                          Python floats (binary64, round to nearest even) and prints, per input,
#                                          "<input bits> <binary64 bits before narrow> <binary64 bits after narrow>"
# Standard library only; no file is written by either mode.
import math, struct, sys
from fractions import Fraction

NAME = 'log32'
OPS = {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}
def lvl(c): return ('n', ('add', ('const', c), ('mul', ('var', 'w'), ('var', 'n'))))
STAGES = [   # (name, input variable, steps [(target, tree)], output variable)
    ('rt', 'y', [('y', ('sqrt', ('var', 'y')))], 'y'),
    ('z', 'y', [('z', ('div', ('sub', ('var', 'y'), ('const', '1.0')), ('add', ('var', 'y'), ('const', '1.0'))))], 'z'),
    ('p', 'z', [('w', ('mul', ('var', 'z'), ('var', 'z'))), ('n', ('add', ('const', '21.0'), ('mul', ('var', 'w'), ('const', '15.0'))))]
               + [lvl(c) for c in ('35.0', '105.0')]
               + [('p', ('div', ('mul', ('var', 'z'), ('var', 'n')), ('const', '105.0')))], 'p'),
]
NEAR = ('0.9375', '1.0625')            # near := NEAR[0] <= x and x <= NEAR[1]   (15/16 and 17/16)
BRANCH = {True: (0, '2.0'), False: (12, '8192.0')}    # near -> (how many times stage rt is applied, the constant k)
# the function: narrow(k * p(z(rt^reps(x)))) with (reps, k) = BRANCH[near]; the product is written k * p, k on the left

def stage(name): return next(s for s in STAGES if s[0] == name)

# ---- rendering 1: Python floats ---------------------------------------------------------------------------------
def py_tree(e, env):
    if e[0] == 'var': return env[e[1]]
    if e[0] == 'const': return float(e[1])
    if e[0] == 'sqrt': return math.sqrt(py_tree(e[1], env))
    a, b = py_tree(e[1], env), py_tree(e[2], env)
    return a + b if e[0] == 'add' else a - b if e[0] == 'sub' else a * b if e[0] == 'mul' else a / b
def py_stage(name, v):
    _, var, ss, out = stage(name); env = {var: v}
    for t, e in ss: env[t] = py_tree(e, env)
    return env[out]
def py_pre(x):
    """The binary64 value before narrow."""
    near = float(NEAR[0]) <= x and x <= float(NEAR[1])
    reps, k = BRANCH[near]; y = x
    for _ in range(reps): y = py_stage('rt', y)
    return float(k) * py_stage('p', py_stage('z', y))
KK, MM, TT, HH = 536870913.0, 1.5 * 2.0 ** -97, 2.0 ** -126, 2.0 ** -150
def py_narrow(v):                       # p32/Graphs.v's narrow, operation for operation
    if abs(v) <= HH: return v * 0.0
    if abs(v) < TT: return (v + MM) - MM
    c = KK * v
    return c - (c - v)
def py_g(x): return py_narrow(py_pre(x))
def f32(u): return struct.unpack('<f', struct.pack('<I', u))[0]
def bits(d): return struct.unpack('<Q', struct.pack('<d', d))[0]
def py():
    src = sys.stdin.buffer if sys.argv[2] == '-' else open(sys.argv[2], 'rb')
    out = []
    for line in src.read().decode('ascii').split('\n'):
        f = line.split()
        if not f or (len(f) == 2 and f[0] != 'log'): continue
        u = int(f[-1], 16); x = f32(u); v = py_pre(x)
        out.append('%08x %016x %016x' % (u, bits(v), bits(py_narrow(v))))
    sys.stdout.buffer.write((chr(10).join(out) + chr(10)).encode('ascii'))

# ---- rendering 2: the Coq graph ---------------------------------------------------------------------------------
def coq_const(s):
    q = Fraction(s)
    assert q > 0 and q.denominator & (q.denominator - 1) == 0, s      # a positive dyadic constant: exact in binary64
    return '%d' % q.numerator if q.denominator == 1 else '(%d / %d)' % (q.numerator, q.denominator)
def coq_tree(e, env):
    if e[0] == 'var': return env[e[1]]
    if e[0] == 'const': return coq_const(e[1])
    if e[0] == 'sqrt': return '(RN64 (sqrt %s))' % coq_tree(e[1], env)
    return '(RN64 (%s %s %s))' % (coq_tree(e[1], env), OPS[e[0]], coq_tree(e[2], env))
def coq_text():
    """Every binary64 operation is one RN64 of its exact operands; a stage is a definition of its input, its steps
    substituted in order; the two comparisons are Rle_dec on the input itself, with no rounding."""
    L = ['(* Generated by log32/emit_log32.py coq; do not edit. The operation graph of log32 in the FLT model of binary64 (no',
         '   overflow, no sign of zero): the same table emit_log32.py evaluates with Python floats in its py mode.',
         '   log32_near: 15/16 <= x <= 17/16. log32_rt: one square root. log32_y: x itself if near, otherwise twelve square',
         '   roots of x. log32_z: (y - 1) / (y + 1). log32_p: (z * N(z*z)) / 105 with N(w) = 105 + w(35 + w(21 + w*15)).',
         '   log32_k: 2 if near, otherwise 8192. *)',
         'From Coq Require Import Reals.', 'From Flocq Require Import Core.', 'From MKF.p32 Require Import Graphs.', 'Open Scope R_scope.', '']
    lo, hi = coq_const(NEAR[0]), coq_const(NEAR[1])
    L.append('Definition %s_near (x : R) : bool :=' % NAME)
    L.append('  if Rle_dec %s x then (if Rle_dec x %s then true else false) else false.' % (lo, hi))
    for name, var, ss, out in STAGES:
        env = {var: var}
        for t, e in ss: env[t] = coq_tree(e, env)
        body = env[out]
        if body.startswith('(') and body.endswith(')'): body = body[1:-1]
        L.append('Definition %s_%s (%s : R) : R := %s.' % (NAME, name, var, body))
    def chain(reps):
        c = 'x'
        for _ in range(reps): c = '%s_rt %s' % (NAME, c if c == 'x' else '(%s)' % c)
        return c
    L.append('Definition %s_y (x : R) : R := if %s_near x then %s else %s.' % (NAME, NAME, chain(BRANCH[True][0]), chain(BRANCH[False][0])))
    L.append('Definition %s_k (x : R) : R := if %s_near x then %s else %s.' % (NAME, NAME, coq_const(BRANCH[True][1]), coq_const(BRANCH[False][1])))
    L += ['', 'Definition g_%s (x : R) : R := narrow (RN64 (%s_k x * %s_p (%s_z (%s_y x)))).' % (NAME, NAME, NAME, NAME, NAME)]
    return chr(10).join(L) + chr(10)
def coq():
    if len(sys.argv) > 2 and sys.argv[2] == '-': sys.stdout.buffer.write(coq_text().encode('utf-8'))
    else: print('usage: emit_log32.py coq -   (prints Graph.v; this script writes no file)'); sys.exit(2)

if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] in ('coq', 'py'): {'coq': coq, 'py': py}[sys.argv[1]]()
    else: print('usage: emit_log32.py coq - | py <file|->'); sys.exit(2)
