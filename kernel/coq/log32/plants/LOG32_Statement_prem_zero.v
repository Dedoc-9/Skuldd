(* The LOG32 statement: a CANDIDATE, drafted 2026-11-15 before any proof of it and before any compilation of this
   file. Author: the assistant. Definitions only: this file holds no proof script and assumes nothing. It is not
   adopted: whether it says what it should is the owner's judgment. Graph.v is generated by log32/emit_log32.py from
   the one table that its py mode evaluates with Python floats. A prototype of the same graph was run on 140,618
   binary32 inputs before this file was written, so the statement was not written blind to the implementation.

   MODEL. Flocq's FLT formats: binary64 as FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper
   exponent bound, so there is no overflow in the model, and the sign of a zero is not seen. Every binary64 operation
   of the graph is the round-to-nearest-even (RN64) of the exact result of its operands; the two comparisons of the
   graph are comparisons of real numbers. ln is the natural logarithm of Coq's standard library (Reals).

   WHAT IT SAYS.
   LOG32          for every positive binary32 number x below 2^128, the graph's value g_log32 x is a faithful binary32
                  rounding of ln x: the binary32 number just below ln x or the one just above it, or ln x itself when
                  that is a binary32 number (at x = 1, where ln x = 0, the value is 0).
   LOG32_FINITE   for the same x, g_log32 x is a finite binary32 number: in the binary32 format and of magnitude at
                  most FMAX32, the largest finite binary32 number (p32r's finite32).
   LOG32_ALL      both.

   THE PREMISES, one line each.
     format32 x             x is a number of the binary32 format (FLT(-149, 24)); subnormal numbers are included.
     0 < x                  x is positive. ln is the real logarithm; zero and negative x are outside the statement.
     x < bpow radix2 128    x is below 2^128, so, with format32 x, at most FMAX32: a finite binary32 number. It is
                            needed and not decoration: format32 has no upper exponent bound, and for a huge x twelve
                            square roots do not bring x near 1, where alone the graph's series is accurate.

   WHAT IT DOES NOT SAY.
   - Nothing about the sign of a zero. At x = 1 the value is the real number 0; whether a program returns +0 or -0
     there is not stated, and the model cannot state it.
   - Nothing about inputs outside the premises: x = 0, negative x, a value that is not a binary32 number, x at or
     above 2^128. In particular it does not say the graph returns minus infinity at 0 (it does not: the model has
     no infinity, and the graph's value at 0 is an ordinary negative number) nor NaN for a negative x.
   - Nothing about NaN or infinite inputs or results: the model has neither.
   - Nothing about a program, a compiler, a processor or a rounding-mode register: that some program performs these
     operations, in this order, on these constants, in binary64, in round to nearest even, is not stated here. Nor
     that Python's floats, used to test the table, do.
   - It is not correct rounding. Which of the two neighbours of ln x is returned is not said: not that it is the
     nearer one.
   - Overflow is absent from the model. That no binary64 operation of the graph overflows on these inputs, and that
     none of them raises an exception, is not stated here. (The intermediate values are all of magnitude below
     2^128, the input's own bound; that is an argument of DESIGN.md, not a sentence of this file.)
   - Nothing about monotonicity, about the error in units in the last place, or about speed.

   WHAT IT TRUSTS. Coq's kernel and its standard library's real numbers (their axioms: the tier's expected list of
   four); Flocq's definitions of the FLT format and of rounding; that RN64 and RN32 are what binary64 and binary32
   round to nearest even do on finite numbers away from overflow; the reader's reading of Graph.v against the table
   in emit_log32.py; f32's faithful32 and format32 and p32r's finite32 and FMAX32, whose statement files are frozen
   in their own folders. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.p32r Require Import P32R_Statement.
From MKF.log32 Require Import Graph.
Open Scope R_scope.

Definition LOG32 : Prop :=
  forall x : R, format32 x -> 0 <= x -> x < bpow radix2 128 -> faithful32 (ln x) (g_log32 x).

Definition LOG32_FINITE : Prop :=
  forall x : R, format32 x -> 0 < x -> x < bpow radix2 128 -> finite32 (g_log32 x).

Definition LOG32_ALL : Prop := LOG32 /\ LOG32_FINITE.
