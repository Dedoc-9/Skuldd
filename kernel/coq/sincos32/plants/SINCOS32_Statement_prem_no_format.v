(* The SINCOS32 statement: a CANDIDATE, 2026-11-16. It is draft 2 (read twice as draft 1) with one line added at the
   owner's word, SINCOS32_UNIT; the two EXACT lines are kept (the owner left striking them to the assistant's
   judgment: they are where a reader sees the exact points and where a proof must show them). Not adopted.
   (earlier lead line: for the owner's reading and for a reader that did not write it.
   Written before its proof and before any compilation.) Author: the assistant.

   The angle is in TURNS: sinturn32 x is about sin (2 pi x) and costurn32 x about cos (2 pi x); x = 1 is one full
   turn, x = 1/4 a quarter turn. The graph is Graph.v, generated by sincos32/emit_sincos32.py from one table of steps (the definitions of
   ext-work/sincos32/src/DRAFT2-Graph.v, which the owner named); against the prototype proto_turn2.py it leaves out
   one exact operation, the polynomial's first product u * 1.0, as sin32's and cos32's graphs do. Model: Flocq's FLT formats, binary64
   as FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper exponent bound, so no overflow, and the sign
   of a zero is not seen. sin, cos and PI are the standard library's.

   WHAT IT SAYS.
   SINTURN32        for EVERY number x of the binary32 format (no bound on its magnitude; the model's format has no
                    largest number, so this includes magnitudes of 2^128 and more, which no binary32 datum holds), g_sinturn32 x is a faithful binary32 rounding
                    of sin (2 pi x): one of the two binary32 values that bracket it, and that value itself when it
                    is a binary32 number.
   COSTURN32        the same for g_costurn32 x and cos (2 pi x).
   SINTURN32_EXACT  three lines without pi, so that a reader need not know sin (2 pi x) at these points:
                    if 2x is a whole number (a whole or a half turn), the result is exactly 0;
                    if x is a whole number plus 1/4, exactly 1; if x is a whole number plus 3/4, exactly -1.
   COSTURN32_EXACT  if x is a whole number, exactly 1; if x is a whole number plus 1/2, exactly -1;
                    if 2x is a whole number plus 1/2 (a quarter or three-quarter turn), exactly 0.
                    These six lines are NOT independent claims: each follows from SINTURN32 or COSTURN32 and the
                    value of sin or cos at that point, because a faithful rounding of a binary32 number is that
                    number. They are stated so the exact points can be read off, and so a proof must show them.
   SINCOS32_UNIT    both results have magnitude at most 1. Not independent: it follows from the first two, since 1
                    and -1 are binary32 numbers and |sin|, |cos| <= 1. Stated because a caller may rely on it
                    (a square root of 1 - s * s, an inverse sine).
   SINCOS32_FINITE  both results are finite binary32 numbers (in the format, magnitude at most FMAX32). Not
                    independent either: it follows from the first two, |sin|, |cos| <= 1 and p32r's FAITHFUL_FINITE.
   SINCOS32_ALL     all of them.

   WHAT IT DOES NOT SAY.
   - Anything about RADIANS. A caller holding an angle in radians must divide by 2 pi first, and that division
     rounds; nothing here covers it. sin32 and cos32 (radians, small domains) are other statements.
   - That a large x is a USEFUL angle. Every binary32 x with |x| >= 2^23 is a whole number of turns (and from 2^22
     a whole number of half turns, from 2^21 of quarter turns). From 2^23 on the results are exactly 0 (sine) and 1
     (cosine); between 2^21 and 2^23 they are exactly 0, 1 or -1. Correct, and coarse. A phase that grows without bound must be kept by the caller in a wider type and brought here small.
   - Anything for a NaN or an infinity (the model has neither; an IEEE input "of magnitude 2^128" is an infinity).
     The prototype's operations give 1 for the cosine of an infinity and a NaN for its sine; an IEEE-level statement must decide that case, and this one cannot see it.
   - The SIGN OF A ZERO. The model has one zero. The prototype's operations give zeros whose sign differs from the
     sinPi / cosPi convention at some exact points (for example at x = 1/2); only an IEEE-level statement can say
     which sign, and the graph there will need a selection step this graph does not have.
   - Anything about a program, a compiler, a machine or the floating-point control state. It is about the Coq graph;
     that a program computes that graph with IEEE binary64 operations is another layer and is not shown here.
   - That the exact points of the two EXACT lines are the only inputs whose true value is a binary32 number (they
     are, for a binary32 x; it is not stated), or that the result is not zero away from them.
   - Anything about sin32's or cos32's statements. SIN32 and COS32 are neither used nor implied.
   - That the result is correctly rounded. Faithful allows either neighbour, and which one is not said.
   - That the two results go together: nothing says g_sinturn32 x squared plus g_costurn32 x squared is near 1 beyond
     what the two faithful roundings give, nor that sinturn32 x equals costurn32 (x - 1/4).
   - That the graph is odd or even in x, periodic, or monotone inside a quarter turn.
   - That no binary64 operation of the graph overflows or underflows (overflow is absent from the model).
   - That every step called exact in the graph's comment is exact. One is not: 1 - |r| rounds when r is tiny and
     not zero (cosine of a tiny x). The statement does not depend on which steps are exact; a proof must not assume it.
   - Anything about pi beyond what sin, cos and PI mean. That cos32_PH is close to pi/2 is a fact a proof needs
     (cos32's PiBound has it); it is not stated here. cos32_PL is not used.

   OF THE STEPS BEFORE narrow, ONE CONSTANT IS NOT A WHOLE NUMBER (narrow has its own three): cos32_PH = 7074237752028440 / 2^52 (0x1.921fb54442d18p+0), the same
   definition cos32 uses, imported (the import brings cos32_PL too; it is not used). The others are whole: 1.5 * 2^52 = 6755399441055744, 2^23 = 8388608, 4, 1, 0 and
   sin32's divisors.

   WHAT IT TRUSTS. Coq's kernel and the tier's four axioms; Flocq's generic_format, FLT_exp and round; the standard
   library's sin, cos, PI, Rabs and IZR; format32 and faithful32 from f32, finite32 from p32r, RN64 and narrow from
   p32, sin32_sq and sin32_poly from sin32, cos32_PH from cos32; and that the graph is the graph meant.

   THE PREMISE.  format32 x   x is a number of the binary32 format, of any magnitude. There is no other premise. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.p32r Require Import P32R_Statement.
From MKF.sincos32 Require Import Graph.
Open Scope R_scope.

Definition SINTURN32 : Prop :=
  forall x : R, format32 x -> faithful32 (sin (2 * PI * x)) (g_sinturn32 x).

Definition COSTURN32 : Prop :=
  forall x : R, faithful32 (cos (2 * PI * x)) (g_costurn32 x).

Definition SINTURN32_EXACT : Prop :=
  forall (x : R) (n : Z), format32 x ->
    (2 * x = IZR n -> g_sinturn32 x = 0) /\
    (x = IZR n + 1 / 4 -> g_sinturn32 x = 1) /\
    (x = IZR n + 3 / 4 -> g_sinturn32 x = -1).

Definition COSTURN32_EXACT : Prop :=
  forall (x : R) (n : Z), format32 x ->
    (x = IZR n -> g_costurn32 x = 1) /\
    (x = IZR n + 1 / 2 -> g_costurn32 x = -1) /\
    (2 * x = IZR n + 1 / 2 -> g_costurn32 x = 0).

Definition SINCOS32_UNIT : Prop :=
  forall x : R, format32 x -> Rabs (g_sinturn32 x) <= 1 /\ Rabs (g_costurn32 x) <= 1.

Definition SINCOS32_FINITE : Prop :=
  forall x : R, format32 x -> finite32 (g_sinturn32 x) /\ finite32 (g_costurn32 x).

Definition SINCOS32_ALL : Prop :=
  SINTURN32 /\ COSTURN32 /\ SINTURN32_EXACT /\ COSTURN32_EXACT /\ SINCOS32_UNIT /\ SINCOS32_FINITE.
